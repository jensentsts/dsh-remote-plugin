import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const candidates = [process.env.DSH_BUILD_ROOT, resolve(root, '../../dsh')].filter(Boolean)
let esbuild
for (const base of candidates) {
  const require = createRequire(resolve(base, 'package.json'))
  for (const name of ['esbuild', resolve(base, 'node_modules/.pnpm/esbuild@0.28.1/node_modules/esbuild')]) {
    try { esbuild = require(name); break } catch {}
  }
  if (esbuild) break
}
if (!esbuild) throw new Error('Install esbuild in the development checkout, or set DSH_BUILD_ROOT to a DSH source checkout containing it')
// Explicit foundation build only. Keep FsError/other shared services external;
// the two inherited filesystem implementations must come from the reviewed release.
const aliasRoot = process.env.DSH_FS_ALIAS_SOURCE_ROOT ? resolve(process.env.DSH_FS_ALIAS_SOURCE_ROOT) : undefined
if (aliasRoot) {
  const manifest = JSON.parse(readFileSync(resolve(aliasRoot, 'package.json'), 'utf8'))
  if (manifest.version !== '0.2.2-rc.1') throw new Error('DSH_FS_ALIAS_SOURCE_ROOT must be the exact DSH 0.2.2-rc.1 source checkout')
}
const fsSources = aliasRoot ? new Map([
  ['@deepseek-ai/dsh-fs-local', resolve(aliasRoot, 'packages/fs/fs-local/src/index.ts')],
  ['@deepseek-ai/dsh-fs-sandbox', resolve(aliasRoot, 'packages/fs/fs-sandbox/src/index.ts')],
]) : new Map()
for (const name of ['client', 'server', 'link', 'protocol', 'peer-fs', 'file-reference', 'mesh']) {
  const entry = resolve(root, `src/${name}.ts`)
  if (!existsSync(entry)) throw new Error(`Missing build entry: ${name}`)
  const plugins = name === 'peer-fs' && aliasRoot ? [{ name: 'exact-filesystem-foundation', setup(build) {
    build.onResolve({ filter: /^@deepseek-ai\// }, args => {
      const source = fsSources.get(args.path)
      if (source) {
        if (!existsSync(source)) throw new Error(`Missing exact filesystem source: ${source}`)
        return { path: source }
      }
      return { path: args.path, external: true }
    })
  } }] : []
  await esbuild.build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node',
    external: plugins.length ? ['zod', 'chokidar', 'koffi'] : ['@deepseek-ai/*', 'zod', 'chokidar', 'koffi'], plugins,
    target: 'es2022', outfile: resolve(root, `lib/${name}.js`) })
  console.log(`Built ${name}${plugins.length ? ' (exact filesystem foundation)' : ''}`)
  if (name === 'peer-fs') {
    // One ESM generation for both public subpaths. A second inlined bundle would
    // define a second FederatedFileSystem/SandboxedFileSystem generation, so the
    // alias is a re-export of the same module URL instead of a byte copy.
    writeFileSync(resolve(root, 'lib/peer-fs-0.5.2.js'), [
      '// Generated by tools/build.mjs from src/peer-fs.ts; do not edit by hand.',
      '// Re-export everything so the named FederatedFileSystem and the shared',
      '// Cordis/FileSystem/FsError identity come from the same ESM generation.',
      "export * from './peer-fs.js'",
      "export { default } from './peer-fs.js'",
      '',
    ].join('\n'))
    console.log('Synced lib/peer-fs-0.5.2.js to lib/peer-fs.js')
  }
}
